"use client";

import { useEffect, useState } from "react";
import { CartesianGrid, ComposedChart, ErrorBar, Legend, Line, ResponsiveContainer, Scatter, Tooltip, XAxis, YAxis } from "recharts";

type Table = { columns: string[]; rows: (string | number)[][] };
type Block = { title: string; text?: string; table?: Table; callout?: { tone?: "stop" | "info"; text: string };
               kpis?: { value: string; label: string }[] };
type Report = { title: string; intro: string; blocks: Block[]; generated?: string };

function Blocks({ r }: { r: Report }) {
  return (
    <>
      {r.title && (
        <section className="section">
          <h1 style={{ fontSize: 34, marginBottom: 10 }}>{r.title}</h1>
          <p className="lede">{r.intro}</p>
          {r.generated && <p className="small muted">Numbers generated by {r.generated}</p>}
        </section>
      )}
      {r.blocks.map((b, i) => (
        <section className="section" key={i}>
          <div className="section-head"><h2>{b.title}</h2></div>
          {b.text && <p>{b.text}</p>}
          {b.kpis && (
            <div className="kpis" style={{ margin: "8px 0 16px" }}>
              {b.kpis.map((k) => <div className="kpi" key={k.label}><div className="bignum">{k.value}</div><div className="small">{k.label}</div></div>)}
            </div>
          )}
          {b.callout && <p className={`callout ${b.callout.tone ?? ""}`}>{b.callout.text}</p>}
          {b.table && (
            <div className="table-scroll">
              <table className="plain">
                <thead><tr>{b.table.columns.map((c) => <th key={c}>{c}</th>)}</tr></thead>
                <tbody>{b.table.rows.map((row, j) => <tr key={j}>{row.map((c, k) => <td key={k} className={typeof c === "number" ? "num" : ""}>{c}</td>)}</tr>)}</tbody>
              </table>
            </div>
          )}
        </section>
      ))}
    </>
  );
}

export function TestingView() {
  const [r, setR] = useState<Report | null>(null);
  const [err, setErr] = useState(false);
  useEffect(() => { fetch("/eval/testing.json").then((x) => x.json()).then(setR).catch(() => setErr(true)); }, []);
  if (err) return <p className="section">The evaluation summary is missing. Run <code>python3 evaluation/build_report.py</code>.</p>;
  if (!r) return <p className="section muted">Loading the evaluation summary…</p>;
  return <Blocks r={r} />;
}

type Pt = { t: number; v: number };
type Est = { t: number; est: number; lo: number; hi: number };
type Series = { title: string; note?: string; x_label: string; truth: Pt[]; estimates: { name: string; color: string; points: Est[] }[] };
type Real = Report & { series?: Series };

export function RealFootageView() {
  const [r, setR] = useState<Real | null>(null);
  const [err, setErr] = useState(false);
  useEffect(() => { fetch("/eval/real_footage.json").then((x) => x.json()).then(setR).catch(() => setErr(true)); }, []);
  if (err) return <p className="section">The real-footage results are missing. Run <code>python3 evaluation/build_report.py</code>.</p>;
  if (!r) return <p className="section muted">Loading the real-footage results…</p>;
  const s = r.series;
  return (
    <>
      <Blocks r={{ ...r, blocks: r.blocks.slice(0, 1) }} />
      {s && (
        <section className="section">
          <div className="section-head"><h2>{s.title}</h2></div>
          {s.note && <p className="small muted">{s.note}</p>}
          <div style={{ width: "100%", height: 360 }}>
            <ResponsiveContainer>
              <ComposedChart margin={{ top: 8, right: 16, bottom: 26, left: 0 }}>
                <CartesianGrid stroke="#d6dce1" />
                <XAxis dataKey="t" type="number" domain={[0, "dataMax"]} fontSize={13}
                       label={{ value: s.x_label, position: "insideBottom", offset: -14, fontSize: 13 }} />
                <YAxis fontSize={13} label={{ value: "km/h", angle: -90, position: "insideLeft", fontSize: 13 }} />
                <Tooltip formatter={(v: number | number[]) => (Array.isArray(v) ? "" : v.toFixed(0))} labelFormatter={(l) => `${Number(l).toFixed(1)} s`} />
                <Legend verticalAlign="top" height={44} />
                <Line data={s.truth.map((p) => ({ t: p.t, truth: p.v * 3.6 }))} dataKey="truth" name="Measured by the car (CAN speed)"
                      stroke="#7a8691" dot={false} strokeWidth={1.5} isAnimationActive={false} />
                {s.estimates.map((e) => (
                  <Scatter key={e.name} name={e.name} fill={e.color} isAnimationActive={false}
                           data={e.points.map((p) => ({ t: p.t, [e.name]: p.est * 3.6, err: [(p.est - p.lo) * 3.6, (p.hi - p.est) * 3.6] }))}
                           dataKey={e.name}>
                    <ErrorBar dataKey="err" direction="y" stroke={e.color} width={0} />
                  </Scatter>
                ))}
              </ComposedChart>
            </ResponsiveContainer>
          </div>
        </section>
      )}
      <Blocks r={{ ...r, title: "", intro: "", blocks: r.blocks.slice(1) }} />
    </>
  );
}

"""
Final report generation (brief section 23, restructured per
docs/definition_of_done.md to lead with avoidability, not just speed).

Takes the pipeline's structured result dict (as produced by
evaluation/scripts/run_causality_feasibility.run_collision_pipeline, or
the single-vehicle equivalent in run_feasibility) and renders the
human-readable report. Pure formatting/templating -- no new analysis
happens here; every number in the report must already exist in the
input dict, so the report can never say more than the pipeline actually
established.
"""
from datetime import datetime, timezone


DISCLAIMER = (
    "**This report is generated by an automated computer-vision analysis tool "
    "(Stradiva, working title). It is a decision-support / preliminary "
    "reconstruction aid, not certified forensic testimony and not a legal "
    "determination of fault. All figures are estimates with stated "
    "uncertainty, derived from the stated assumptions; human expert review "
    "is required before any of this is used in a legal, insurance, or "
    "disciplinary context.**"
)


def _fmt(value, unit="", decimals=1, none_text="not available"):
    if value is None:
        return none_text
    if isinstance(value, bool):
        return str(value)
    return f"{value:.{decimals}f}{unit}"


def render_collision_report(result, scenario_name="incident"):
    lines = []
    lines.append(f"# Stradiva Reconstruction Report — {scenario_name}")
    lines.append(f"\n_Generated {datetime.now(timezone.utc).strftime('%Y-%m-%d %H:%M UTC')}_\n")
    lines.append(DISCLAIMER)

    status = result.get("status", "UNKNOWN")
    recon = result.get("reconstructability", {})
    causality = result.get("causality", {})

    # --- Top-line summary (per definition_of_done.md: avoidability leads, not speed) ---
    lines.append("\n## Summary\n")
    if status != "RECONSTRUCTABLE":
        lines.append(
            f"**This footage was determined NOT reconstructable to a quantitative standard.** "
            f"See Reconstruction Quality below for why."
        )
        return "\n".join(lines)

    verdict = causality.get("verdict", "UNKNOWN")
    verdict_sentence = {
        "AVOIDABLE": "the collision **appears to have been physically avoidable** under the modeled assumptions",
        "NOT_AVOIDABLE": "the collision **appears to have been physically unavoidable** under the modeled assumptions",
        "INSUFFICIENT_EVIDENCE": "**there is insufficient evidence to determine avoidability**",
    }.get(verdict, "avoidability could not be determined")
    lines.append(
        f"Based on reconstructed vehicle motion, {verdict_sentence}. "
        f"Reconstruction confidence: **{recon.get('overall', 'n/a')}/100** "
        f"({recon.get('verdict', 'n/a')})."
    )

    # --- What happened / how vehicles moved ---
    lines.append("\n## What Happened\n")
    v_speed = causality.get("striking_vehicle_speed_at_earliest_observed_mps")
    ttc = causality.get("time_to_collision_at_earliest_observed_s")
    lines.append(
        f"- Following/striking vehicle's earliest reliably observed speed: "
        f"{_fmt(v_speed, ' m/s')} ({_fmt(v_speed * 3.6 if v_speed else None, ' km/h')})."
    )
    unc = result.get("uncertainty", {})
    ci = unc.get("striking_vehicle_speed_ci90_mps")
    if ci and ci[0] is not None:
        lines.append(
            f"  - **90% confidence interval: {ci[0]:.1f}–{ci[1]:.1f} m/s** "
            f"({ci[0]*3.6:.0f}–{ci[1]*3.6:.0f} km/h). "
            f"Dominant uncertainty source(s): {', '.join(unc.get('dominant_sources', [])) or 'n/a'}. "
            f"See `docs/uncertainty_calibration.md` for how this interval is derived and calibrated."
        )
    lines.append(f"- Time-to-collision at earliest observed point: {_fmt(ttc, ' s')}.")
    if causality.get("braking_detected"):
        lines.append(
            f"- Sustained braking detected, beginning approximately "
            f"{_fmt(causality.get('braking_onset_time_before_impact_s'), ' s')} before impact."
        )
    else:
        lines.append("- No sustained braking detected in the observed pre-impact window.")
    if causality.get("steering_detected"):
        lines.append(
            f"- Sustained lateral maneuver ({causality.get('steering_direction')}) detected, "
            f"beginning approximately {_fmt(causality.get('steering_onset_time_before_impact_s'), ' s')} before impact."
        )
    else:
        lines.append("- No sustained lateral maneuver (steering) detected in the observed pre-impact window.")

    # --- Avoidability assessment (top-level section, per addendum) ---
    lines.append("\n## Avoidability Assessment\n")
    lines.append(f"**Verdict: {verdict}**\n")
    lines.append(causality.get("narrative", "No narrative available."))
    assumptions = causality.get("assumptions", {})
    if assumptions:
        lines.append(
            f"\n_Modeled assumptions: max deceleration "
            f"{assumptions.get('max_decel_mps2', 'n/a')} m/s², "
            f"reaction time {assumptions.get('reaction_time_s', 'n/a')} s. "
            f"These are stated priors, not measured properties of this specific vehicle/road._"
        )
    lines.append(f"\nConfidence in this avoidability conclusion: **{causality.get('confidence', 'n/a')}** "
                  f"(inherited from upstream reconstruction confidence).")

    # --- Contribution factors (physical observations, NOT a fault/blame determination) ---
    cf = causality.get("contribution_factors")
    if cf:
        lines.append("\n### Physical Contribution Factors\n")
        lines.append(
            "_These describe each vehicle's own reconstructed motion against a physical reference. "
            "They are not a fault, responsibility, or blame determination — Stradiva does not identify "
            "which driver caused the collision._\n"
        )
        safe_speed = cf.get("following_vehicle_safe_speed_for_observed_gap_mps")
        pct = cf.get("following_vehicle_speed_vs_safe_speed_pct")
        if safe_speed is not None:
            lines.append(
                f"- Following vehicle's modeled safe speed for the observed gap: {safe_speed} m/s. "
                + (f"Reconstructed speed was **{pct:+.0f}%** relative to that reference." if pct is not None else "")
            )
        lines.append(f"- Lead vehicle deceleration profile: **{cf.get('lead_vehicle_deceleration_classification', 'n/a')}**.")

    # --- Evidence ---
    lines.append("\n## Evidence\n")
    for item in causality.get("evidence", []):
        lines.append(f"- {item}")

    # --- Agentic recovery trace (if used) ---
    agent_trace = result.get("agent_trace")
    if agent_trace:
        lines.append("\n## Agentic Geometry Recovery\n")
        lines.append(
            f"Geometry/scale recovery used {agent_trace.get('n_iterations', 1)} iteration(s) "
            f"before {'succeeding' if agent_trace.get('success') else 'exhausting all candidates'} "
            f"on frame {agent_trace.get('chosen_frame_idx')}.\n"
        )
        for call in agent_trace.get("calls", []):
            if call.get("reasoning"):
                lines.append(f"- **{call['tool']}** ({call['args']}) → {call['result']} — {call['reasoning']}")
            else:
                lines.append(f"- **{call['tool']}** ({call['args']}) → {call['result']}")

    # --- The Skeptic's cross-examination ---
    geometry = result.get("geometry", {})
    skeptic_findings = geometry.get("skeptic_findings")
    if skeptic_findings:
        disputed = geometry.get("skeptic_disputed")
        lines.append("\n## Cross-Examination\n")
        lines.append(
            f"Before this reconstruction was accepted, a second, independent check "
            f"(the Skeptic) tried to find a reason to disagree with it, using evidence "
            f"the Reconstructor's own acceptance test did not use. "
            f"**Verdict: {'DISPUTED' if disputed else 'no contradiction found'}.**\n"
        )
        for f in skeptic_findings:
            mark = "⚠️ DISPUTED" if f.get("disputed") else "cleared"
            lines.append(f"- **{f['check'].replace('_', ' ')}** — {mark}: {f['reason']}")
        if disputed:
            lines.append(
                "\nA disputed finding does not mean the reconstruction is wrong — it means "
                "a real, independent signal disagrees with part of the Reconstructor's own "
                "acceptance test, and the result should be treated with reduced confidence "
                "until a human reviews it."
            )

    # --- Reconstruction quality ---
    lines.append("\n## Reconstruction Quality\n")
    components = recon.get("components", {})
    for k, v in components.items():
        lines.append(f"- {k.capitalize()}: {v}/100")
    lines.append(f"- Overall: **{recon.get('overall', 'n/a')}/100** — {recon.get('verdict', 'n/a')}")

    # --- Tracking ---
    tracking = result.get("tracking", {})
    if tracking:
        lines.append("\n## Vehicle Tracking\n")
        lines.append(
            f"- Vehicle A (lead): {tracking.get('vehicle_a_tracked', 'n/a')} frames tracked, "
            f"{tracking.get('vehicle_a_lost', 'n/a')} lost."
        )
        lines.append(
            f"- Vehicle B (following): {tracking.get('vehicle_b_tracked', 'n/a')} frames tracked, "
            f"{tracking.get('vehicle_b_lost', 'n/a')} lost."
        )

    # --- Limitations ---
    lines.append("\n## Limitations\n")
    lines.append(
        "- Absolute vehicle position is unanchored (no independently-verified landmark); "
        "relative displacement/speed is the reliable output, not absolute world position."
    )
    lines.append(
        "- Vehicle detection uses background-subtraction against a static-camera assumption; "
        "does not yet handle camera motion, occlusion between vehicles, or non-rear-end geometries."
    )
    lines.append(
        "- Avoidability assumes fixed max-deceleration and reaction-time constants (see Assumptions "
        "above) rather than vehicle- or driver-specific values."
    )
    lines.append("- Only braking is currently detected as evasive action; steering is not yet analyzed.")

    # --- Conclusion ---
    lines.append("\n## Conclusion\n")
    lines.append(
        f"This footage supports a {recon.get('verdict', 'n/a').lower().replace('_', ' ')} reconstruction. "
        f"{verdict_sentence.capitalize()}. This is a physical, evidence-based assessment only — "
        f"it does not determine legal fault."
    )

    return "\n".join(lines)
